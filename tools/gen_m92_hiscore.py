#!/usr/bin/env python3
"""m92-pi: build core/m92_hiscore.inc from MAME's hiscore plugin data.

    python3 tools/gen_m92_hiscore.py <mame>/plugins/hiscore/hiscore.dat \\
            core/m92_games.inc > core/m92_hiscore.inc
    python3 tools/gen_m92_hiscore.py <mame>/plugins/hiscore/hiscore.dat \\
            core/m90_games.inc m90 > core/m90_hiscore.inc

Keeps the entries of the sets in m92_games.inc, as MAME reads them: a set
without its own entry has no hiscore saving (no fall-back to the parent).
Only main CPU program-space rows are expected; @delay and prefill are refused.
"""
import re, sys

dat_path, games_path = sys.argv[1], sys.argv[2]
prefix = sys.argv[3] if len(sys.argv) > 3 else 'm92'
sets = re.findall(r'\{ "([a-z0-9]+)", "([a-z0-9]*)", "', open(games_path).read())
names = [s for s, _ in sets]

entries = {}
pending, rows = [], []

def flush():
	global pending, rows
	if pending and rows:
		for n in pending:
			entries.setdefault(n, list(rows))
	pending, rows = [], []

for raw in open(dat_path, encoding='latin-1'):
	line = re.sub(r'[ \t\r\n]*;.*$', '', raw).strip()
	if not line:
		continue
	if line.startswith('@'):
		rows.append(line)
	elif re.match(r'^[a-z0-9_,]+:$', line):
		if rows:
			flush()
		pending.append(line[:-1])
flush()

out = []
out.append('// Generated by tools/gen_m92_hiscore.py from MAME plugins/hiscore/hiscore.dat')
out.append('// (MAME hiscore plugin data, Leezer and contributors). Do not edit by hand.')
out.append('')
table = []
for n in names:
	if n not in entries:
		continue
	parsed = []
	for r in entries[n]:
		if r.startswith('@delay'):
			sys.exit(f'{n}: @delay not supported')
		f = r[1:].split(',')
		if f[0] != ':maincpu' or f[1] != 'program':
			sys.exit(f'{n}: {r}: only :maincpu,program')
		if len(f) > 6 and f[6]:
			sys.exit(f'{n}: {r}: prefill not supported')
		addr, size, first, last = (int(x, 16) for x in f[2:6])
		parsed.append((addr, size, first, last))
	out.append(f'static const m92_hiscore_row {prefix}_hirows_{n}[] = {{' if prefix != 'm92' else f'static const m92_hiscore_row hirows_{n}[] = {{')
	for addr, size, first, last in parsed:
		out.append(f'\t{{ 0x{addr:05x}, 0x{size:03x}, 0x{first:02x}, 0x{last:02x} }},')
	out.append('\t{ 0, 0, 0, 0 }')
	out.append('};')
	table.append((n, len(parsed)))

out.append('')
out.append(f'static const m92_hiscore {prefix}_hiscores[] = {{')
for n, k in table:
	out.append(f'\t{{ "{n}", {prefix + "_" if prefix != "m92" else ""}hirows_{n}, {k} }},')
out.append('};')
print('\n'.join(out))
missing = [n for n in names if n not in entries]
print(f'{len(table)} sets with hiscores; none for: {" ".join(missing)}', file=sys.stderr)
