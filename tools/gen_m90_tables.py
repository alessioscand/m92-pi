#!/usr/bin/env python3
"""m92-pi: build core/m90_games.inc from MAME's Irem M90/M97/M99 driver.

    python3 tools/gen_m90_tables.py <mame>/src/mame/irem > core/m90_games.inc

Reads m90.cpp (ROM_START blocks, INPUT_PORTS, machine configurations, GAME lines)
and iremipt.h, and writes plain C++ tables: ROM lists with CRCs, DIP switches with
their settings and defaults, controls and the per-game hardware choices. The
bootlegs (different video and sound hardware) are left out.
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from irem_ports import load_inputs, resolve, nice, cstr

src = sys.argv[1]
drv = open(os.path.join(src, 'm90.cpp')).read()
ipt = open(os.path.join(src, 'iremipt.h')).read()

# ---------------------------------------------------------------- input ports
a = drv.index('static INPUT_PORTS_START(')
b = drv.rindex('INPUT_PORTS_END') + len('INPUT_PORTS_END')
inputs = load_inputs(drv[a:b], ipt)

# ---------------------------------------------------------------- ROMs
REGIONS = {'maincpu': 'MAINCPU', 'user1': 'BANK', 'soundcpu': 'SOUNDCPU', 'gfx1': 'GFX', 'm72': 'SAMPLES'}
roms = {}
for m in re.finditer(r'ROM_START\(\s*(\w+)\s*\)(.*?)ROM_END', drv, re.S):
    name, body_ = m.group(1), m.group(2)
    regions = []
    reg = None
    vector = 0
    for line in body_.splitlines():
        line = line.split('//')[0].split('/*')[0].strip()
        r = re.match(r'ROM_REGION(?:16_LE)?\(\s*(0x[0-9a-fA-F]+|CODE_SIZE)\s*,\s*"(\w+)"', line)
        if r:
            size = 0x100000 if r.group(1) == 'CODE_SIZE' else int(r.group(1), 16)
            reg = {'name': r.group(2), 'size': size, 'loads': []}
            regions.append(reg)
            continue
        r = re.match(r'(ROM_LOAD16_BYTE|ROM_LOAD)\(\s*"([^"]+)"\s*,\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*,\s*(?:CRC\((\w+)\)|NO_DUMP)', line)
        if r:
            reg['loads'].append((r.group(2), int(r.group(3), 16), int(r.group(4), 16),
                                 r.group(1) == 'ROM_LOAD16_BYTE', int(r.group(5), 16) if r.group(5) else 0))
            continue
        r = re.match(r'ROM_COPY\(\s*"maincpu"\s*,\s*(0x[0-9a-fA-F]+)\s*,\s*0xffff0\s*,\s*0x10\s*\)', line)
        if r:
            vector = int(r.group(1), 16)
        elif line.startswith('ROM_'):
            reg['unsupported'] = True
    roms[name] = (regions, vector)

# ---------------------------------------------------------------- machines
configs = {}
for m in re.finditer(r'void m90_state::(\w+)\(machine_config &config\)\s*\{(.*?)\n\}', drv, re.S):
    configs[m.group(1)] = m.group(2)

def visarea(expr):
    return [eval(x, {}) for x in expr.split(',')]

def machine_props(cfg):
    p = {'table': None, 'vis': None, 'm99': False, 'quizf1': False, 'bootleg': False}
    body_ = configs.get(cfg, '')
    base = re.search(r'^\s*(\w+)\(config\);', body_, re.M)
    if base and base.group(1) in configs:
        p.update(machine_props(base.group(1)))
    t = re.search(r'set_decryption_table\((\w+)_decryption_table\)', body_)
    if t: p['table'] = t.group(1)
    v = re.search(r'set_visarea\(([^;]*)\);', body_)
    if v: p['vis'] = visarea(v.group(1))
    if 'm99_sound_cpu_io_map' in body_: p['m99'] = True
    if 'quizf1_main_cpu_map' in body_: p['quizf1'] = True
    if 'V30(config.replace()' in body_: p['bootleg'] = True
    return p

games = []
for m in re.finditer(r'^GAME\(\s*(\d+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*"([^"]*)"\s*,\s*"([^"]*)"\s*,\s*([^)]*)\)', drv, re.M):
    year, name, parent, mcfg, inp, cls, init, rot, manu, desc, flags = m.groups()
    props = machine_props(mcfg)
    if props['bootleg'] or 'bootleg' in manu:
        continue              # Dynablaster and Bomber Lord bootlegs, Dice: other hardware
    games.append(dict(year=year, name=name, parent=parent, mcfg=mcfg, inp=inp, init=init, rot=rot,
                      manu=manu, desc=desc, props=props))

# ---------------------------------------------------------------- output
o = []
w = o.append
w('// Generated by tools/gen_m90_tables.py from MAME src/mame/irem/m90.cpp (BSD-3-Clause,')
w('// copyright-holders: Bryan McPhail). Do not edit by hand.')
w('')
used_inputs = [i for i in dict.fromkeys(g['inp'] for g in games)]
for inp in sorted(used_inputs):
    ports = resolve(inputs, inp)
    dips = list(ports.get('DSW', {}).get('dips', []))
    def lockey(d):
        m = re.match(r'SW(\d+):(\d+)', d['loc'])
        return (int(m.group(1)), int(m.group(2))) if m else (9, 9)
    dips.sort(key=lockey)
    w('static const m92_dip_setting dipset_m90_%s[] = {' % inp)
    for d in dips:
        for v, n in d['settings']:
            w('\t{ 0x%04x, %s },' % (v, cstr(nice(n))))
    w('\t{ 0, nullptr }\n};')
    w('static const m92_dip dips_m90_%s[] = {' % inp)
    idx = 0
    for d in dips:
        cond = d['cond']
        w('\t{ 0, 0x%04x, 0x%04x, %s, %s, %d, %d, 0x%04x, %d, 0x%04x },' % (
            d['mask'], d['default'], cstr(nice(d['name'])), cstr(d['loc']),
            idx, len(d['settings']),
            cond[0] if cond else 0, (1 if cond[1] == 'EQUALS' else 2) if cond else 0, cond[2] if cond else 0))
        idx += len(d['settings'])
    w('\t{ 0, 0, 0, nullptr, nullptr, 0, 0, 0, 0, 0 }\n};')
    nbut = 0; players = 2
    for pn in ('P1_P2', 'P3_P4'):
        for mask, (t, pl, s) in ports.get(pn, {}).get('bits', {}).items():
            mb = re.match(r'IPT_BUTTON(\d)', t)
            if mb: nbut = max(nbut, int(mb.group(1)))
            if pl and t != 'IPT_UNUSED': players = max(players, pl)
    dsw_def = 0xffff
    for d in ports.get('DSW', {}).get('dips', []):
        dsw_def = (dsw_def & ~d['mask']) | d['default']
    w('static const m92_inputs inputs_m90_%s = { dips_m90_%s, dipset_m90_%s, 0x%04x, 0xff, %d, %d };\n' % (
        inp, inp, inp, dsw_def, players, nbut))

for g in games:
    regions, vector = roms[g['name']]
    w('static const m92_rom roms_m90_%s[] = {' % g['name'])
    for r in regions:
        assert not r.get('unsupported'), (g['name'], r['name'])
        for fn, off, size, b16, crc in r['loads']:
            w('\t{ M90_REG_%s, %s, 0x%06x, 0x%06x, %d, 0x%08x },' % (REGIONS[r['name']], cstr(fn), off, size, 1 if b16 else 0, crc))
    w('\t{ 0, nullptr, 0, 0, 0, 0 }\n};')

w('static const m90_game m90_games[] = {')
for g in games:
    regions, vector = roms[g['name']]
    regs = {r['name']: r['size'] for r in regions}
    p = g['props']
    x0, x1, y0, y1 = p['vis']
    w('\t{ %s, %s, %s, %s, %s, roms_m90_%s, &inputs_m90_%s, %s, %d, %d, %d, %d, %d, %d, 0x%x, { 0x%x, 0x%x, 0x%x, 0x%x, 0x%x } },' % (
        cstr(g['name']), cstr(g['parent'] if g['parent'] != '0' else ''), cstr(g['desc']), cstr(g['year']), cstr(g['manu']),
        g['name'], g['inp'], (p['table'] + '_decryption_table') if p['table'] else 'nullptr',
        1 if p['m99'] else 0, 1 if p['quizf1'] else 0, x0, x1 - x0 + 1, y0, y1 - y0 + 1, vector,
        regs.get('maincpu', 0), regs.get('user1', 0), regs.get('soundcpu', 0), regs.get('gfx1', 0), regs.get('m72', 0)))
w('};')
print('\n'.join(o))
